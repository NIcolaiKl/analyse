# 1.4 Работа с формами (6 баллов)
# ============================================================
def task_1_4():
    """Преобразование тензора из 24 элементов в разные формы."""
    x = torch.arange(24).float()
    print("Исходный тензор:", x.shape, "| numel =", x.numel())

    shapes = [(2, 12), (3, 8), (4, 6), (2, 3, 4), (2, 2, 2, 3)]
    results = []
    for shape in shapes:
        try:
            y = x.reshape(shape)
            # Проверка корректности преобразования
            assert y.numel() == x.numel(), "Ошибка: количество элементов изменилось"
            print(f"reshape{shape}: OK, shape = {y.shape}")
            results.append(y)
        except RuntimeError as e:
            print(f"Не удалось преобразовать в {shape}: {e}")

    return results


