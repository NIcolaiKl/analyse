# 1.3 Индексация и срезы (6 баллов)
# ============================================================
def task_1_3():
    """Индексация и срезы тензора 5x5x5."""
    x = torch.arange(125).reshape(5, 5, 5).float()
    print("Исходный тензор x.shape =", x.shape)

    # Первая строка (по первому измерению, все остальные элементы)
    first_row = x[0]  # форма (5,5)
    print("\nПервая строка (x[0]):\n", first_row)

    # Последний столбец (по последнему измерению) для каждой "страницы"
    last_col = x[:, :, -1]  # форма (5,5)
    print("\nПоследний столбец (x[:, :, -1]):\n", last_col)

    # Подматрица 2x2 из центра тензора (по двум последним измерениям)
    center_sub = x[:, 1:3, 1:3]  # форма (5,2,2)
    print("\nЦентральная подматрица 2x2 (x[:, 1:3, 1:3]):\n", center_sub)

    # Все элементы с чётными индексами по всем измерениям
    even_elements = x[::2, ::2, ::2]  # форма (3,3,3)
    print("\nЭлементы с чётными индексами (x[::2, ::2, ::2]).shape =", even_elements.shape)

    return x, first_row, last_col, center_sub, even_elements


