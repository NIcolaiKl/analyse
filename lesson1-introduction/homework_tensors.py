import torch


# ============================================================
# 1.1 Создание тензоров (7 баллов)
# ============================================================
def task_1_1():
    """Создание тензоров различных форм и способов заполнения."""
    # Тензор 3x4 со случайными числами от 0 до 1
    t_random = torch.rand(3, 4)
    print("1) Тензор 3x4 (rand 0..1):\n", t_random)

    # Тензор 2x3x4, заполненный нулями
    t_zeros = torch.zeros(2, 3, 4)
    print("\n2) Тензор 2x3x4 (zeros):\n", t_zeros)

    # Тензор 5x5, заполненный единицами
    t_ones = torch.ones(5, 5)
    print("\n3) Тензор 5x5 (ones):\n", t_ones)

    # Тензор 4x4 с числами от 0 до 15 через reshape
    t_arange = torch.arange(16).reshape(4, 4)
    print("\n4) Тензор 4x4 (arange 0..15):\n", t_arange)

    return t_random, t_zeros, t_ones, t_arange


