# 1.2 Операции с тензорами (6 баллов)
# ============================================================
def task_1_2():
    """Операции: транспонирование, matmul, поэлементное умножение, сумма."""
    torch.manual_seed(0)
    A = torch.rand(3, 4)  # 3x4
    B = torch.rand(4, 3)  # 4x3

    # Транспонирование A: 4x3
    A_T = A.T
    print("A.T shape:", A_T.shape)

    # Матричное умножение A (3x4) @ B (4x3) -> 3x3
    matmul_AB = torch.matmul(A, B)
    print("A @ B shape:", matmul_AB.shape)

    # Поэлементное умножение A (3x4) * B.T (3x4) -> 3x4
    # Проверяем совместимость форм
    if A.shape == B.T.shape:
        elementwise = A * B.T
        print("A * B.T shape:", elementwise.shape)
    else:
        print("Формы не совпадают для поэлементного умножения!")

    # Сумма всех элементов A
    total_sum = A.sum().item()
    print(f"Сумма всех элементов A: {total_sum:.4f}")

    return A, B, A_T, matmul_AB, elementwise, total_sum


